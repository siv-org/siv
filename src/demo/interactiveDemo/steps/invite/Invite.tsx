import { Mail } from 'lucide-react'
import { useState } from 'react'
import { generateAuthToken } from 'src/crypto/generate-auth-tokens'

import { ExploreGroup, ExploreSection, ExploreTopic } from '../../shared/ExploreSection'
import { PrimaryButton } from '../../shared/PrimaryButton'
import { SecondaryButton } from '../../shared/SecondaryButton'
import { InviteQRCode } from './InviteQRCode'

export function Invite({ auth, onContinue }: { auth: string; onContinue: () => void }) {
  const [attack, setAttack] = useState<'lost' | 'used' | null>(null)
  const [layers, setLayers] = useState(() => new Set<string>())
  const [remediated, setRemediated] = useState(false)
  const [replacementAuth] = useState(() => generateAuthToken())
  const [stuffing, setStuffing] = useState<'guess' | 'reuse' | 'roll' | null>(null)
  const [topic, setTopic] = useState<'attack' | 'delivery' | 'layers' | 'stuffing' | 'token' | null>(null)
  const authLayers = [
    ['Drawn signature', 'Compare with the voter’s registration record'],
    ['ID + selfie', 'Higher-assurance identity check'],
    ['IP geolocation', 'Flag or limit unexpected locations'],
    ['Time-based code', 'Require a second possession factor'],
  ]
  const voterCodeProperties = [
    'required to vote',
    'unique per voter',
    'generated by election admin',
    'infeasible to guess',
    'can only be used once',
    'if necessary, election admin can invalidate individual Voter Codes & generate new ones',
    'used Voter Codes can be audited after the election',
  ]

  return (
    <div>
      <div className="px-4 py-5 rounded-xl bg-h26-bg sm:px-6">
        <p className="flex items-center gap-2 text-[10px] text-h26-green">
          <Mail aria-hidden className="size-5 shrink-0" strokeWidth={1.5} />
          <span className="font-mono26 uppercase tracking-[0.14em]">Vote Invitation Sent via Postal Mail</span>
        </p>
        <p className="mt-5 text-[1rem] text-h26-text">
          You’re invited to vote in <b>City Mayoral Election</b>.
        </p>
        <p className="mt-1 text-[0.85rem] text-h26-textSecondary">This invitation is unique to you.</p>

        <div className="mt-5 flex flex-col items-center gap-4 rounded-xl border border-black/[0.07] bg-white p-4 sm:flex-row sm:items-center sm:justify-center sm:gap-8">
          <InviteQRCode auth={auth} />
          <div className="text-center sm:text-left">
            <p className="text-[0.8rem] text-h26-textSecondary">Scan the QR code, or visit</p>
            <button
              className="mt-1 font-medium underline text-h26-green underline-offset-2"
              onClick={onContinue}
              type="button"
            >
              local.gov/election
            </button>
            <p className="mt-3 text-[0.75rem] text-h26-textSecondary">and enter your Voter Code:</p>
            <p className="mt-1 font-mono26 text-[1rem] font-medium tracking-[0.12em] text-h26-text">{auth}</p>
          </div>
        </div>
      </div>

      <PrimaryButton className="mt-5" onClick={onContinue}>
        Open ballot
      </PrimaryButton>

      <ExploreSection>
        <div className="grid gap-2 mt-3 sm:grid-cols-2">
          <ExploreTopic
            onClick={() => setTopic(topic === 'token' ? null : 'token')}
            open={topic === 'token'}
            subtitle="Your unique, one-use voting credential"
            title="What is my Voter Code?"
          />
          <ExploreTopic
            onClick={() => setTopic(topic === 'delivery' ? null : 'delivery')}
            open={topic === 'delivery'}
            subtitle="How invitations reach eligible voters"
            title="Why postal mail?"
          />
        </div>

        {topic === 'token' && (
          <div className="p-4 mt-3 rounded-xl bg-h26-bg">
            <p className="text-[0.8rem] leading-relaxed text-h26-textSecondary">
              The invitation’s job is to get each voter their Voter Code — the one-time credential that lets them cast.
              Yours in this demo: <span className="font-medium font-mono26 text-h26-text">{auth}</span>
            </p>
            <p className="mt-4 text-[0.78rem] font-medium text-h26-text">Key Properties of Voter Codes</p>
            <ul className="mt-2 space-y-1.5">
              {voterCodeProperties.map((item) => (
                <li className="flex gap-2 text-[0.78rem] text-h26-textSecondary" key={item}>
                  <span className="mt-1.5 size-1 shrink-0 rounded-full bg-h26-green" />
                  <span>{item}</span>
                </li>
              ))}
            </ul>
            <p className="mt-3 text-[0.72rem]">
              <a className="text-h26-green hover:underline" href="/faq#1p1v" target="_blank">
                How does SIV ensure One Vote per Person?
              </a>
            </p>
          </div>
        )}

        {topic === 'delivery' && (
          <div className="p-4 mt-3 rounded-xl bg-h26-bg">
            <p className="text-[0.8rem] leading-relaxed text-h26-textSecondary">
              Postal mail is familiar, tied to a registered address, and can match today’s paper process. It is one
              delivery channel—not a requirement of SIV.
            </p>
            <p className="mt-4 text-[0.78rem] font-medium text-h26-text">Other ways to deliver a Voter Code:</p>
            <div className="grid gap-2 mt-2 sm:grid-cols-3">
              {[
                ['Email or SMS', 'Fast and affordable when contact details are already verified'],
                ['Secure digital channel', 'Use an existing government or organization account'],
                ['In person', 'Useful for high-assurance or replacement credentials'],
              ].map(([label, description]) => (
                <div className="px-3 py-2 bg-white rounded-lg border border-black/[0.07]" key={label}>
                  <p className="text-[0.76rem] font-medium text-h26-text">{label}</p>
                  <p className="mt-0.5 text-[0.68rem] text-h26-textSecondary">{description}</p>
                </div>
              ))}
            </div>
            <p className="mt-3 text-[0.72rem] text-h26-textSecondary">
              Jurisdictions can combine channels or choose different ones for different voters.
            </p>
          </div>
        )}

        <ExploreGroup title="Safeguards">
          <div className="grid gap-2 mt-3 sm:grid-cols-2">
            <ExploreTopic
              onClick={() => setTopic(topic === 'layers' ? null : 'layers')}
              open={topic === 'layers'}
              subtitle="Add identity checks to your authentication policy"
              title="How can voter identity be checked?"
            />
            <ExploreTopic
              onClick={() => setTopic(topic === 'attack' ? null : 'attack')}
              open={topic === 'attack'}
              subtitle="See how revocation and replacement work"
              title="What if my Voter Code is lost or stolen?"
            />
            <ExploreTopic
              onClick={() => setTopic(topic === 'stuffing' ? null : 'stuffing')}
              open={topic === 'stuffing'}
              subtitle="Explore Voter Code checks and voter-roll audits"
              title="Could someone submit extra votes?"
            />
          </div>

          {topic === 'layers' && (
            <div className="p-4 mt-3 rounded-xl bg-h26-bg">
              <p className="text-[0.8rem] leading-relaxed text-h26-textSecondary">
                Delivery gets the credential to the voter. Additional checks can raise confidence that the intended
                voter is the person using it.
              </p>
              <p className="mt-4 text-[0.78rem] font-medium text-h26-text">Build an authentication policy:</p>
              <div className="grid gap-2 mt-2 sm:grid-cols-2">
                {authLayers.map(([label, description]) => (
                  <button
                    aria-pressed={layers.has(label)}
                    className={`rounded-lg border px-3 py-2 text-left transition-colors ${
                      layers.has(label)
                        ? 'border-h26-green/40 bg-white text-h26-text'
                        : 'border-black/[0.07] bg-white/60 text-h26-textSecondary hover:border-h26-green/30'
                    }`}
                    key={label}
                    onClick={() =>
                      setLayers((prev) => {
                        const next = new Set(prev)
                        if (next.has(label)) next.delete(label)
                        else next.add(label)
                        return next
                      })
                    }
                    type="button"
                  >
                    <span className="block text-[0.76rem] font-medium">
                      {layers.has(label) ? '✓ ' : '+ '}
                      {label}
                    </span>
                    <span className="mt-0.5 block text-[0.68rem] opacity-70">{description}</span>
                  </button>
                ))}
              </div>
              <p className="mt-3 text-[0.72rem] text-h26-textSecondary">
                Policy: Postal invitation
                {[...layers].map((layer) => ` + ${layer}`).join('')}
              </p>
              <p className="mt-3 text-[0.72rem]">
                <a className="text-h26-green hover:underline" href="/protocol#1" target="_blank">
                  Protocol
                </a>
                {' · '}
                <a
                  className="text-h26-green hover:underline"
                  href="https://docs.siv.org/authentication"
                  rel="noreferrer"
                  target="_blank"
                >
                  Authentication details
                </a>
              </p>
            </div>
          )}

          {topic === 'attack' && (
            <div className="p-4 mt-3 rounded-xl bg-h26-bg">
              <p className="text-[0.78rem] font-medium text-h26-text">Replace a compromised credential</p>
              <p className="mt-2 text-[0.75rem] leading-relaxed text-h26-textSecondary">
                An election administrator can revoke a Voter Code and issue a replacement after re-authenticating the
                voter. Try a scenario to see the steps.
              </p>
              <p className="mt-4 text-[0.75rem] font-medium text-h26-text">Try a scenario</p>
              <div className="flex flex-wrap gap-2 mt-2">
                {[
                  ['lost', 'Voter Code lost or stolen'],
                  ['used', 'Someone voted first'],
                ].map(([id, label]) => (
                  <button
                    aria-pressed={attack === id}
                    className={`rounded-full border px-3 py-2 text-[0.72rem] transition-colors ${
                      attack === id
                        ? 'border-h26-green/40 bg-white font-medium text-h26-green'
                        : 'border-black/10 bg-white/60 text-h26-textSecondary hover:border-h26-green/30'
                    }`}
                    key={id}
                    onClick={() => {
                      setAttack(id as 'lost' | 'used')
                      setRemediated(false)
                    }}
                    type="button"
                  >
                    {label}
                  </button>
                ))}
              </div>

              {attack && !remediated && (
                <div className="pl-3 mt-4 border-l-2 border-red-300">
                  <p className="text-[0.78rem] font-medium text-red-800">
                    {attack === 'lost'
                      ? 'Until it is revoked, whoever holds the Voter Code could try to vote.'
                      : 'The one-use rule rejects your attempt because the Voter Code was already used.'}
                  </p>
                  <p className="mt-2 text-[0.75rem] leading-relaxed text-h26-textSecondary">
                    The admin re-authenticates the voter, invalidates the old credential and any linked submission, then
                    issues a replacement. Every change leaves an audit trail.
                  </p>
                  <SecondaryButton className="mt-3" onClick={() => setRemediated(true)}>
                    Revoke + issue replacement
                  </SecondaryButton>
                </div>
              )}

              {attack && remediated && (
                <div className="px-3 py-3 mt-4 bg-white rounded-lg border border-h26-green/30">
                  <p className="text-[0.78rem] font-medium text-h26-green">Replacement issued</p>
                  <p className="mt-2 font-mono26 text-[0.72rem] text-h26-muted line-through">Old: {auth}</p>
                  <p className="mt-1 font-mono26 text-[0.78rem] text-h26-text">Replacement: {replacementAuth}</p>
                  <p className="mt-2 text-[0.7rem] text-h26-textSecondary">
                    The old Voter Code is rejected; the voter can cast once with the replacement.
                  </p>
                </div>
              )}
            </div>
          )}

          {topic === 'stuffing' && (
            <div className="p-4 mt-3 rounded-xl bg-h26-bg">
              <p className="text-[0.78rem] font-medium text-h26-text">One issued Voter Code, one accepted vote</p>
              <p className="mt-2 text-[0.75rem] leading-relaxed text-h26-textSecondary">
                Voter Code checks reject unknown or reused credentials. Checking that registered voters are eligible
                still requires voter-roll audits. Explore what each safeguard addresses.
              </p>
              <p className="mt-4 text-[0.75rem] font-medium text-h26-text">Try a scenario</p>
              <div className="flex flex-wrap gap-2 mt-2">
                {[
                  ['roll', 'Fake voters on the roll'],
                  ['guess', 'Invented Voter Codes'],
                  ['reuse', 'Extra submissions'],
                ].map(([id, label]) => (
                  <button
                    aria-pressed={stuffing === id}
                    className={`rounded-full border px-3 py-2 text-[0.72rem] transition-colors ${
                      stuffing === id
                        ? 'border-h26-green/40 bg-white font-medium text-h26-green'
                        : 'border-black/10 bg-white/60 text-h26-textSecondary hover:border-h26-green/30'
                    }`}
                    key={id}
                    onClick={() => setStuffing(id as 'guess' | 'reuse' | 'roll')}
                    type="button"
                  >
                    {label}
                  </button>
                ))}
              </div>

              {stuffing && (
                <div className="pl-3 mt-4 border-l-2 border-red-300">
                  <p className="text-[0.78rem] font-medium text-red-800">
                    {stuffing === 'roll' && 'Padding the voter roll with fake people.'}
                    {stuffing === 'guess' && 'Trying to invent Voter Codes that were never issued.'}
                    {stuffing === 'reuse' && 'Submitting without a Voter Code, or reusing one already accepted.'}
                  </p>
                  <p className="mt-2 text-[0.75rem] leading-relaxed text-h26-textSecondary">
                    {stuffing === 'roll' &&
                      'Eligibility is still a voter-roll problem — same as paper. The roll can be audited. SIV does not invent who is allowed to vote; it binds each accepted ciphertext to a registered Voter Code.'}
                    {stuffing === 'guess' &&
                      'Voter Codes are generated by the election admin and infeasible to guess. Submissions with unknown Voter Codes are rejected.'}
                    {stuffing === 'reuse' &&
                      'One Voter Code → one accepted ciphertext. A second use is rejected, and every accepted submission is visible on the public board for audit.'}
                  </p>
                  <div className="px-3 py-3 mt-3 bg-white rounded-lg border border-h26-green/30">
                    <p className="text-[0.78rem] font-medium text-h26-green">
                      {stuffing === 'roll' && 'Defense: audit the voter roll'}
                      {stuffing === 'guess' && 'Defense: only issued Voter Codes are accepted'}
                      {stuffing === 'reuse' && 'Defense: one Voter Code, one accepted vote'}
                    </p>
                  </div>
                </div>
              )}

              <p className="mt-3 text-[0.72rem]">
                <a className="text-h26-green hover:underline" href="/faq#1p1v" target="_blank">
                  How does SIV ensure One Vote per Person?
                </a>
              </p>
            </div>
          )}
        </ExploreGroup>
      </ExploreSection>
    </div>
  )
}
